package Generator

import java.io.PrintWriter
import java.nio.file.{Files, Paths}

/**
  * A generated SQL job: one `WITH ... SELECT * FROM <last operator>;` statement in standard SQL,
  * written to `<jobName>.sql`. The operators arrive as CTE fragments ([[AbstractSQLJob.cte]]) and a
  * sink marker ([[AbstractSQLJob.sink]]) from [[Generator.DatasetJob.AbstractSQLTableOperatorManager]].
  *
  * `createProject` also writes `schema.sql` (the `CREATE TABLE` statements of the dataset) next to
  * the jobs, once.
  *
  * @param schema DDL of the dataset's tables
  */
case class AbstractSQLJob(jobBody: String, jobName: String, dataset: String, schema: String) extends AbstractJob {

  // NB: only constructor parameters and defs here, AbstractJob calls fillBody() during construction
  override def fillBody(): String = {
    val parts = jobBody.split(AbstractSQLJob.CteMarker).map(_.trim).filter(_.nonEmpty).toSeq
    val sinks = parts.flatMap(p => AbstractSQLJob.SinkLine.findFirstMatchIn(p).map(_.group(1)))
    if (sinks.size != 1) throw new Exception(s"SQL job $jobName: expected exactly one sink, found ${sinks.size}")
    val ctes = parts.map(p => AbstractSQLJob.SinkLine.replaceAllIn(p, "").trim).filter(_.nonEmpty)
    s"""-- Generated by DataFarm from the $dataset schema: $jobName
       |WITH
       |${ctes.mkString(",\n")}
       |SELECT * FROM ${sinks.head};
       |""".stripMargin
  }

  override def fillSBT(): String = ""

  override def createProject(projectPath: String): Unit = {
    val path = Paths.get(projectPath, s"$jobName.sql")
    println(s"Saving SQL job to $path")
    write(path.toString, filledBody)
    val ddl = Paths.get(projectPath, "schema.sql")
    if (Files.notExists(ddl)) write(ddl.toString, schema)
  }

  private def write(path: String, content: String): Unit = {
    val w = new PrintWriter(new java.io.File(path), "UTF-8")
    try w.write(content) finally w.close()
  }
}

object AbstractSQLJob {
  val CteMarker = "--#cte#--"
  private val SinkMarker = "--#sink#--"
  private val SinkLine = (java.util.regex.Pattern.quote(SinkMarker) + """ (\w+)""").r

  /** One operator as a CTE `name AS (query)`. */
  def cte(name: String, query: String): String = s"\n$CteMarker\n$name AS (\n  $query\n)\n"

  /** The job's result is the output of operator `name`. */
  def sink(name: String): String = s"\n$CteMarker\n$SinkMarker $name\n"
}
