package Generator

import java.io.PrintWriter
import java.nio.file.Paths

/**
  * Created by researchuser7 on 2020-03-17.
  *
  * A generated Wayang job: one self-contained `<jobName>.scala` file that compiles against
  * Apache Wayang main (see [[WayangJobTemplate]] for its structure).
  *
  * @param title   dataset name used in the Wayang job name, e.g. "TPC-H"
  * @param parsers extra top-level definitions written into the job file, e.g. the dataset's
  *                CSV parsers object
  */
case class AbstractWayangJob(jobBody: String, jobName: String, saveExecutionPlan: Boolean = false,
                             title: String = "DataFarm", parsers: String = "") extends AbstractJob {

  // NB: only constructor parameters and defs here, AbstractJob calls fillBody() during construction

  override def fillBody(): String =
    WayangJobTemplate.render(jobName, title, s"Wayang job generated by DataFarm ($title).", jobBody, parsers)

  /** Wayang jobs are single files compiled against Wayang; there is no per-job sbt project. */
  override def fillSBT(): String = ""

  override def createProject(projectPath: String): Unit = {
    val path = Paths.get(projectPath, s"$jobName.scala")
    println(s"Saving Wayang job file to $path")
    val w = new PrintWriter(path.toFile, "UTF-8")
    try w.write(filledBody) finally w.close()
  }
}
