package Generator

import java.io.PrintWriter
import java.nio.file.{Files, Paths}

import Generator.DatasetJob.ParserCode

/**
  * A generated Spark (RDD API) job: a standalone object with a `main` that builds the plan, runs it
  * with a `count()` action and reports the row count and run time. If an output folder is given,
  * it also writes `<jobName>.json` with the run time and the RDD lineage (`toDebugString`), the
  * Spark counterpart of the execution plans DataFarm stores for Flink jobs.
  *
  * The jobs parse their input themselves (object `<jobName>Parsers` in the same file), so they
  * only need spark-core. `createProject` also writes a `build.sbt` next to the jobs, so the whole
  * folder builds with `sbt package`.
  *
  * @param parsers object name => Scala source of the parser object
  * @param dataset name of the dataset, for the generated comment
  */
case class AbstractSparkJob(jobBody: String, jobName: String, parsers: String => String, dataset: String) extends AbstractJob {

  // NB: only constructor parameters and defs here, AbstractJob calls fillBody() during construction
  def parsersObject: String = jobName + "Parsers"

  override def fillBody(): String =
    AbstractSparkJob.JOB_TEMPLATE
      .replace("//#job_name#//", jobName)
      .replace("//#dataset#//", dataset)
      .replace("//#body#//", jobBody.replace(ParserCode.Token, parsersObject))
      .replace("//#parsers#//", parsers(parsersObject))

  override def fillSBT(): String = AbstractSparkJob.SBT_TEMPLATE

  override def createProject(projectPath: String): Unit = {
    val path = Paths.get(projectPath, s"$jobName.scala")
    println(s"Saving Spark job file to $path")
    write(path.toString, filledBody)
    val sbt = Paths.get(projectPath, "build.sbt")
    if (Files.notExists(sbt)) write(sbt.toString, filledSBT)
  }

  private def write(path: String, content: String): Unit = {
    val w = new PrintWriter(new java.io.File(path), "UTF-8")
    try w.write(content) finally w.close()
  }
}

object AbstractSparkJob {

  val Package = "datafarm.generated.spark"

  val SBT_TEMPLATE: String =
    s"""name := "datafarm-spark-jobs"
       |
       |version := "0.1"
       |
       |scalaVersion := "2.12.18"
       |
       |libraryDependencies += "org.apache.spark" %% "spark-core" % "3.5.3" % "provided"
       |""".stripMargin

  val JOB_TEMPLATE: String =
    s"""package $Package
  |
  |import org.apache.spark.{SparkConf, SparkContext}
  |import org.apache.spark.rdd.RDD
  |
  |/**
  |  * Generated by DataFarm from the //#dataset#// schema.
  |  *
  |  * spark-submit --class $Package.//#job_name#// <jar> <datapath/> [planOutputDir]
  |  */
  |object //#job_name#// {
  |
  |  def main(args: Array[String]): Unit = {
  |    val datapath = args(0)
  |    val sc = new SparkContext(new SparkConf().setAppName("//#job_name#//"))
  |    try {
  |      val result = buildPlan(sc, datapath)
  |      val start = System.currentTimeMillis()
  |      val rows = result.count()
  |      val netRunTime = System.currentTimeMillis() - start
  |      println("//#job_name#//: " + rows + " rows in " + netRunTime + " ms")
  |      if (args.length > 1) {
  |        def str(s: String) = "\\"" + s.flatMap {
  |          case '"' => "\\\\\\""; case '\\\\' => "\\\\\\\\"; case '\\n' => "\\\\n"; case c if c < ' ' => " "; case c => c.toString
  |        } + "\\""
  |        val out = new java.io.PrintWriter(new java.io.File(args(1), "//#job_name#//.json"), "UTF-8")
  |        try out.write("{\\"job\\": " + str("//#job_name#//") + ", \\"netRunTime\\": " + netRunTime +
  |          ", \\"rows\\": " + rows + ", \\"lineage\\": " + str(result.toDebugString) + "}\\n")
  |        finally out.close()
  |      }
  |    } finally sc.stop()
  |  }
  |
  |  def buildPlan(sc: SparkContext, datapath: String): RDD[_] = {
  |
  |   //#body#//
  |
  |  }
  |}
  |
  |//#parsers#//
  """.stripMargin
}
