package Generator.DatasetJob.job

import java.io.PrintWriter
import java.nio.file.Paths

import Generator.AbstractJob
import Generator.DatasetJob.ParserCode

/**
  * A generated Wayang job over the JOB/IMDB data.
  *
  * Same structure as [[Generator.AbstractWayangJob]] (a `GeneratableJob` whose `buildPlan` returns
  * the final `DataQuanta`), plus an object `<jobName>Parsers` in the same file that turns IMDB CSV
  * lines into tuples. Each job file is therefore self-contained: it needs no JOB-specific classes
  * on the Wayang side.
  *
  * @param tables tables read by the job; parsers are generated only for these
  */
case class AbstractWayangJOBJob(jobBody: String, jobName: String, saveExecutionPlan: Boolean = false, tables: Seq[String] = Seq())
  extends AbstractJob {

  // NB: only constructor parameters and defs here, AbstractJob calls fillBody() during construction
  def parsersObject: String = jobName + "Parsers"

  override def fillBody(): String =
    AbstractWayangJOBJob.JOB_TEMPLATE
      .replace("//#job_name#//", jobName)
      .replace("//#body#//", jobBody.replace(ParserCode.Token, parsersObject))
      .replace("//#parsers#//", AbstractWayangJOBJob.parsersCode(parsersObject, tables))

  override def fillSBT(): String = ""

  override def createProject(projectPath: String): Unit = {
    val path = Paths.get(projectPath, s"$jobName.scala")
    println(s"Saving Wayang job file to $path")
    val w = new PrintWriter(path.toFile, "UTF-8")
    try w.write(filledBody) finally w.close()
  }
}

